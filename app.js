const $ = (sel) => document.querySelector(sel);
const $$ = (sel) => document.querySelectorAll(sel);
const SECTIONS = $$(".section, .hero");

/* ---------- language ---------- */
let lang =
  localStorage.getItem("lang") ||
  (navigator.language && navigator.language.toLowerCase().startsWith("id") ? "id" : "en");
let typedRoles = I18N[lang].hero_typed_roles;

function setLang(next) {
  lang = I18N[next] ? next : "en";
  localStorage.setItem("lang", lang);
  document.documentElement.setAttribute("lang", lang);

  $$("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    if (I18N[lang][k]) el.textContent = I18N[lang][k];
  });
  $$("[data-i18n-ph]").forEach((el) => {
    const k = el.getAttribute("data-i18n-ph");
    if (I18N[lang][k]) el.setAttribute("placeholder", I18N[lang][k]);
  });

  $$("#langToggle [data-lang]").forEach((s) => s.classList.toggle("active", s.dataset.lang === lang));
  typedRoles = I18N[lang].hero_typed_roles;
  if (!typeLoopRunning) typeLoop();
}

$("#langToggle").addEventListener("click", () => setLang(lang === "en" ? "id" : "en"));

/* ---------- theme ---------- */
function setTheme(mode) {
  document.documentElement.setAttribute("data-theme", mode);
  localStorage.setItem("theme", mode);
  $("#iconMoon").style.display = mode === "dark" ? "block" : "none";
  $("#iconSun").style.display = mode === "dark" ? "none" : "block";
}

$("#themeToggle").addEventListener("click", () =>
  setTheme(document.documentElement.getAttribute("data-theme") === "dark" ? "light" : "dark")
);

/* ---------- typed text ---------- */
let typeLoopRunning = false;
const typedEl = $("#typedText");
let roleIdx = 0;
let charIdx = 0;
let removing = false;

function typeLoop() {
  if (!typedEl || typeLoopRunning) return;
  typeLoopRunning = true;

  const step = () => {
    const word = typedRoles[roleIdx % typedRoles.length];
    if (!removing) {
      charIdx++;
      typedEl.textContent = word.slice(0, charIdx);
      if (charIdx === word.length) {
        removing = true;
        setTimeout(step, 1600);
        return;
      }
      setTimeout(step, 70);
    } else {
      charIdx--;
      typedEl.textContent = word.slice(0, charIdx);
      if (charIdx === 0) {
        removing = false;
        roleIdx++;
        setTimeout(step, 300);
        return;
      }
      setTimeout(step, 45);
    }
  };
  step();
}

/* ---------- nav: scroll state + scrollspy + smooth scroll + mobile ---------- */
const navbar = $("#navbar");
const navLinks = $("#navLinks");
const navLinkEls = $$(".nav-link");

function onScroll() {
  navbar.classList.toggle("scrolled", window.scrollY > 40);

  const pos = window.scrollY + 160;
  SECTIONS.forEach((sec) => {
    const top = sec.offsetTop;
    const bottom = top + sec.offsetHeight;
    if (pos >= top && pos < bottom) {
      navLinkEls.forEach((l) => l.classList.remove("active"));
      const match = $(`.nav-link[href="#${sec.id}"]`);
      if (match) match.classList.add("active");
    }
  });
}

navLinkEls.forEach((link) => {
  link.addEventListener("click", (e) => {
    const target = $(link.getAttribute("href"));
    if (!target) return;
    e.preventDefault();
    window.scrollTo({ top: target.getBoundingClientRect().top + window.scrollY - 70, behavior: "smooth" });
    closeMenu();
  });
});

function closeMenu() {
  navLinks.classList.remove("open");
  $("#hamburger").classList.remove("open");
}

$("#hamburger").addEventListener("click", () => {
  navLinks.classList.toggle("open");
  $("#hamburger").classList.toggle("open");
});

/* ---------- reveal on scroll ---------- */
const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("in-view");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);
$$(".reveal, .timeline-item, .project-card, .skills-group, .about-grid, .contact-grid").forEach((el) =>
  revealObserver.observe(el)
);

/* ---------- init ---------- */
document.addEventListener("DOMContentLoaded", () => {
  $("#year").textContent = new Date().getFullYear();
  setTheme(localStorage.getItem("theme") || "dark");
  setLang(lang);
  typeLoop();
  window.addEventListener("scroll", onScroll, { passive: true });
  onScroll();
});